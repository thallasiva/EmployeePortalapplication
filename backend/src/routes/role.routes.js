const express = require('express');
const controller = require('../controllers/role.controller');
const validate = require('../middleware/validate');
const { namedEntitySchema } = require('../validators/common.validator');
const { authenticate } = require('../middleware/auth');
const { requirePlatformAdmin } = require('../utils/companyScope');
const router = express.Router();
const schema = namedEntitySchema('role_name');
router.use(authenticate);
router.get('/', requirePlatformAdmin, controller.list);
router.get('/:id', requirePlatformAdmin, controller.getOne);
router.post('/', requirePlatformAdmin, validate(schema), controller.create);
router.put('/:id', requirePlatformAdmin, validate(schema.fork(['role_name'], (s) => s.optional())), controller.update);
router.delete('/:id', requirePlatformAdmin, controller.remove);
module.exports = router;
