const express = require('express');
const router  = express.Router();
const c = require('../controllers/workSchedule.controller');
const { authenticate, authorizeRoles } = require('../middleware/auth');
const { requireCompanyModule, requirePermission } = require('../middleware/rbac');
router.use(authenticate);
router.use(requireCompanyModule('attendance'));
router.get('/me', c.getMine);
router.use(authorizeRoles('Admin', 'HR Manager'));
router.get('/', requirePermission('attendance', 'view'), c.listAll);
router.get('/:employeeId', requirePermission('attendance', 'view'), c.getByEmployee);
router.put('/:employeeId', requirePermission('attendance', 'edit'), c.upsert);
router.delete('/:employeeId', requirePermission('attendance', 'edit'), c.remove);
module.exports = router;
