'use strict';

const asyncHandler = require('express-async-handler');
const Joi = require('joi');
const planSvc = require('../../services/recruitment/interviewPlan.service');
const ApiResponse = require('../../utils/ApiResponse');

const questionSchema = Joi.object({
  question_text: Joi.string().trim().min(10).max(1000).required(),
  stage: Joi.string().valid('introduction', 'resume_validation', 'technical', 'scenario', 'domain').default('technical'),
  question_type: Joi.string().valid('experience', 'resume_probe', 'technical', 'practical', 'scenario').default('technical'),
  skill: Joi.string().trim().max(100).allow('', null),
  difficulty: Joi.string().valid('fundamental', 'intermediate', 'proficient', 'advanced', 'senior').default('intermediate'),
  expected_points: Joi.array().items(Joi.string().trim().min(2).max(300)).max(8).default([]),
  time_limit_seconds: Joi.number().integer().min(60).max(900).default(180),
});
const saveSchema = Joi.object({
  questions: Joi.array().items(questionSchema).min(1).max(20).required(),
  duration_minutes: Joi.number().integer().min(10).max(60),
  notes: Joi.string().trim().max(500).allow('', null),
});
const generateSchema = Joi.object({
  question_count: Joi.number().integer().min(4).max(15).default(8),
  duration_minutes: Joi.number().integer().min(10).max(60).default(30),
});

function body(schema, req, res) {
  const { error, value } = schema.validate(req.body || {}, { abortEarly: false, stripUnknown: true });
  if (error) { res.status(400).json({ success: false, message: error.details.map((d) => d.message).join('; ') }); return null; }
  return value;
}

const jobStatuses = asyncHandler(async (_req, res) => {
  new ApiResponse(200, await planSvc.jobPlanStatuses(), 'Job plan statuses fetched').send(res);
});

const listForJob = asyncHandler(async (req, res) => {
  new ApiResponse(200, await planSvc.listForJob(Number(req.params.jobReqId)), 'Interview plans fetched').send(res);
});

const getPlan = asyncHandler(async (req, res) => {
  const plan = await planSvc.getPlan(Number(req.params.planId));
  if (!plan) return res.status(404).json({ success: false, message: 'Interview plan not found' });
  new ApiResponse(200, plan, 'Interview plan fetched').send(res);
});

const generate = asyncHandler(async (req, res) => {
  const v = body(generateSchema, req, res);
  if (!v) return;
  const plan = await planSvc.generateDraft(Number(req.params.jobReqId), req.user.employeeId, { questionCount: v.question_count, durationMinutes: v.duration_minutes });
  new ApiResponse(201, plan, plan.generated_by === 'ai' ? 'Draft generated by AI' : 'Draft generated from the role question bank').send(res);
});

const save = asyncHandler(async (req, res) => {
  const v = body(saveSchema, req, res);
  if (!v) return;
  const plan = await planSvc.saveDraft(Number(req.params.planId), { questions: v.questions, durationMinutes: v.duration_minutes, notes: v.notes });
  new ApiResponse(200, plan, 'Draft saved').send(res);
});

const approve = asyncHandler(async (req, res) => {
  new ApiResponse(200, await planSvc.approve(Number(req.params.planId), req.user.employeeId), 'Interview plan approved').send(res);
});

const revise = asyncHandler(async (req, res) => {
  new ApiResponse(201, await planSvc.reviseApproved(Number(req.params.jobReqId), req.user.employeeId), 'Draft created from the approved plan').send(res);
});

const discard = asyncHandler(async (req, res) => {
  await planSvc.discardDraft(Number(req.params.planId));
  new ApiResponse(200, null, 'Draft discarded').send(res);
});

module.exports = { jobStatuses, listForJob, getPlan, generate, save, approve, revise, discard };
